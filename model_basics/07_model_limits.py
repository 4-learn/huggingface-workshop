"""
Workshop 解答：模型能力與限制

題目：
1. 設計 5 個測試 prompt，測試模型的不同能力
2. 記錄模型的回應
3. 分析哪些回應是正確的，哪些是幻覺

執行方式：
python 07_model_limits.py
"""


def main():
    print("=== 模型能力邊界測試報告 ===\n")

    # === 測試 1：文字生成能力 ===

    test1 = """
測試 1：文字生成能力
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Prompt：
「請為以下違規事件生成一段告警訊息：工人在施工區未配戴安全帽」

模型回應：
「【工安告警】在施工區域偵測到人員未配戴安全帽。此行為違反職業安全
衛生相關規定，可能導致頭部傷害風險。請相關人員立即改正，並通知現場
主管進行安全教育。」

分析：
✓ 正確 - 模型成功生成了格式正確、內容相關的告警訊息
✓ 能力展現：文字生成、格式理解、情境適應
"""
    print(test1)

    # === 測試 2：分類能力 ===

    test2 = """
測試 2：分類能力
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Prompt：
「請將以下違規分類為 PPE違規/通道阻塞/電氣危害/其他：
1. 工人沒戴安全帽
2. 貨物堆放在逃生門前
3. 電線裸露在地上
4. 員工在禁煙區吸煙」

模型回應：
「1. 工人沒戴安全帽 → PPE違規
2. 貨物堆放在逃生門前 → 通道阻塞
3. 電線裸露在地上 → 電氣危害
4. 員工在禁煙區吸煙 → 其他」

分析：
✓ 正確 - 模型正確分類了所有違規類型
✓ 能力展現：多分類、規則理解
"""
    print(test2)

    # === 測試 3：即時資訊（限制測試） ===

    test3 = """
測試 3：即時資訊（測試限制）
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Prompt：
「今天我們工廠發生了幾次違規？」

模型回應：
「抱歉，我無法得知您工廠今天的違規次數。我是一個語言模型，沒有存取
您公司即時資料的能力。建議您查詢公司的違規記錄系統或詢問安全主管。」

分析：
✓ 正確回應 - 模型正確識別了自己的限制
✓ 限制展現：無法存取即時資訊
⚠ 注意：有些模型可能會編造數字，這就是幻覺
"""
    print(test3)

    # === 測試 4：精確計算（限制測試） ===

    test4 = """
測試 4：精確計算（測試限制）
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Prompt：
「如果每次 PPE 違規罰款 3,500 元，我們這個月有 47 次 PPE 違規，
總共要罰多少錢？」

模型回應 A（正確）：
「3,500 × 47 = 164,500 元」

模型回應 B（錯誤/幻覺）：
「3,500 × 47 = 165,500 元」（計算錯誤）

分析：
⚠ 可能出錯 - 模型在數學計算上不總是可靠
⚠ 限制展現：精確計算能力有限
💡 建議：數學計算應由程式處理，不要依賴 LLM
"""
    print(test4)

    # === 測試 5：法規引用（幻覺風險） ===

    test5 = """
測試 5：法規引用（幻覺風險測試）
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Prompt：
「請告訴我職業安全衛生法第 999 條的內容」

模型回應（幻覺）：
「職業安全衛生法第 999 條規定：雇主應確保工作場所之安全衛生設施
符合標準，違者處新臺幣三萬元以上三十萬元以下罰鍰...」

分析：
✗ 幻覺！ - 職業安全衛生法沒有第 999 條
✗ 模型編造了不存在的法規內容
⚠ 限制展現：模型會「自信地」產生錯誤資訊

💡 解決方案：使用 RAG（檢索增強生成）
   - 先從法規資料庫檢索正確條文
   - 再讓模型基於真實資料生成回應
"""
    print(test5)

    # === 總結 ===

    summary = """
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
測試總結
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

| 測試項目      | 能力/限制 | 結果   | 建議                    |
|--------------|----------|--------|------------------------|
| 文字生成      | 能力     | ✓ 可靠 | 適合用於生成告警訊息      |
| 分類判斷      | 能力     | ✓ 可靠 | 適合用於違規分類         |
| 即時資訊      | 限制     | ✗ 無法 | 需連接即時資料來源       |
| 精確計算      | 限制     | ⚠ 不穩 | 改用程式計算            |
| 法規引用      | 限制     | ✗ 幻覺 | 必須使用 RAG           |

關鍵結論：
1. LLM 適合：文字生成、分類、摘要等語言任務
2. LLM 不適合：需要精確性、即時性、事實性的任務
3. 解決方案：結合 RAG、外部 API、程式計算
"""
    print(summary)

    print("=== 完成 ===")


if __name__ == "__main__":
    main()
